"""Admin Routes.

The eight reference-data entities (clients, contacts, producers, installers,
services, materials, tools, equipment) are all plain CRUD over a repository, so
they are declared as :class:`CrudSpec` values and their views are generated by
:func:`register_crud`.

Users stay hand-written: password hashing, username uniqueness and the
self-deletion guard make them different enough that squeezing them into the
generic path would obscure both.
"""

